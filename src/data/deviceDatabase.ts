// Local cache key for newly discovered or user-saved devices
const DISCOVERED_DEVICES_CACHE_KEY = 'adspower_discovered_devices_v1';

export function getCustomCachedDevices(): DeviceSpec[] {
  try {
    const raw = localStorage.getItem(DISCOVERED_DEVICES_CACHE_KEY);
    if (raw) {
      return JSON.parse(raw) as DeviceSpec[];
    }
  } catch (e) {
    console.error('Error reading custom device cache:', e);
  }
  return [];
}

export function saveCustomDeviceToCache(spec: DeviceSpec): void {
  try {
    const existing = getCustomCachedDevices();
    // Check if model already exists
    const filtered = existing.filter(
      (d) => d.model.toLowerCase() !== spec.model.toLowerCase()
    );
    filtered.push(spec);
    localStorage.setItem(DISCOVERED_DEVICES_CACHE_KEY, JSON.stringify(filtered));
  } catch (e) {
    console.error('Error saving custom device to cache:', e);
  }
}

export function getAllDevices(): DeviceSpec[] {
  const cached = getCustomCachedDevices();
  return [...BUILTIN_DEVICE_DATABASE, ...cached];
}
